// Draws the app icon, browser-tab icon and iPhone launch screens from one mark:
// "311" in square block digits over a green rule (STYLE_GUIDE.md). Run after changing
// the mark: npm run icons. Writes into public/ and the launch-screen links in index.html.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { appleSplashScreenSizes } from "@vite-pwa/assets-generator/config";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");

const GROUND = "#141413"; // dark is the default theme, so launch screens are dark too
const INK = "#EDEBE4";
const GREEN = "#34C17B";

// On a 512 grid, built from rectangles: no font needed to render it.
const MARK = `
  <g fill="${INK}">
    <rect x="104" y="140" width="96" height="32"/>
    <rect x="128" y="212" width="72" height="32"/>
    <rect x="104" y="284" width="96" height="32"/>
    <rect x="168" y="140" width="32" height="176"/>
    <rect x="240" y="140" width="32" height="32"/>
    <rect x="272" y="140" width="32" height="176"/>
    <rect x="344" y="140" width="32" height="32"/>
    <rect x="376" y="140" width="32" height="176"/>
  </g>
  <rect x="104" y="356" width="304" height="24" fill="${GREEN}"/>`;

/** `radius` rounds the tile (0 for iOS, which rounds it itself); `scale` shrinks the
 *  mark into Android's maskable safe zone. */
function iconSvg({ radius = 0, scale = 1 } = {}) {
  const inset = (512 * (1 - scale)) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <rect width="512" height="512" rx="${radius}" fill="${GROUND}"/>
  <g transform="translate(${inset} ${inset}) scale(${scale})">${MARK}</g>
</svg>
`;
}

const png = (svg, size) =>
  sharp(Buffer.from(svg), { density: 300 })
    .resize(size, size)
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toBuffer();

/** An .ico holding PNGs (supported by every browser that still asks for one). */
function ico(images) {
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const at = 6 + i * 16;
    header.writeUInt8(size % 256, at);
    header.writeUInt8(size % 256, at + 1);
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(data.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((i) => i.data)]);
}

const square = iconSvg();
const rounded = iconSvg({ radius: 96 });
const maskable = iconSvg({ scale: 0.8 });

writeFileSync(join(pub, "favicon.svg"), rounded);
writeFileSync(join(pub, "apple-touch-icon-180x180.png"), await png(square, 180));
for (const size of [64, 192, 512]) {
  writeFileSync(join(pub, `pwa-${size}x${size}.png`), await png(rounded, size));
}
writeFileSync(join(pub, "maskable-icon-512x512.png"), await png(maskable, 512));
writeFileSync(
  join(pub, "favicon.ico"),
  ico([
    { size: 32, data: await png(rounded, 32) },
    { size: 48, data: await png(rounded, 48) },
  ]),
);

// Launch screens: the ground with the icon in the middle at 112pt, like a native app.
// iOS only shows them for exact screen sizes, so one per iPhone size.
const ICON_PT = 112;
const splashDir = join(pub, "splash");
rmSync(splashDir, { recursive: true, force: true });
mkdirSync(splashDir);
const seen = new Set();
const links = [];
for (const [name, { width, height, scaleFactor }] of Object.entries(appleSplashScreenSizes)) {
  if (!name.startsWith("iPhone") || seen.has(`${width}x${height}`)) continue;
  seen.add(`${width}x${height}`);
  const side = ICON_PT * scaleFactor;
  const tile = await sharp(Buffer.from(iconSvg({ radius: 512 * 0.224 })), { density: 600 })
    .resize(side, side)
    .png()
    .toBuffer();
  const file = `splash/${width}x${height}.png`;
  await sharp({ create: { width, height, channels: 3, background: GROUND } })
    .composite([{ input: tile, gravity: "center" }])
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toFile(join(pub, file));
  const media = [
    `(device-width: ${width / scaleFactor}px)`,
    `(device-height: ${height / scaleFactor}px)`,
    `(-webkit-device-pixel-ratio: ${scaleFactor})`,
    "(orientation: portrait)",
  ].join(" and ");
  links.push(
    `    <link rel="apple-touch-startup-image" media="screen and ${media}" href="/${file}" />`,
  );
}

const indexPath = join(root, "index.html");
const index = readFileSync(indexPath, "utf8");
const start = "<!-- launch screens: generated by scripts/make-icons.mjs -->";
const end = "<!-- /launch screens -->";
writeFileSync(
  indexPath,
  index.replace(
    new RegExp(`${start}[\\s\\S]*?${end}`),
    `${start}\n${links.join("\n")}\n    ${end}`,
  ),
);

console.log(`Icons written; ${links.length} launch screens.`);
