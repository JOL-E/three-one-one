"""Projects, items and their activity log (DECISIONS #3–6).

The database enforces the invariants with constraints; `services.py` checks the
same rules first so callers get a readable message instead of an IntegrityError.
IDs are generated by the app at creation, not by the database (CLAUDE.md).
"""

import uuid

from django.db import models
from django.db.models import Q
from django.db.models.functions import Lower


class ProjectState(models.TextChoices):
    IDEA = "idea", "Idea"
    BUILDING = "building", "Building"
    LIVE = "live", "Live"
    ARCHIVED = "archived", "Archived"


class Project(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    name = models.CharField(max_length=100)
    description = models.TextField(blank=True)
    repo_url = models.URLField(blank=True)
    state = models.CharField(max_length=20, choices=ProjectState.choices, default=ProjectState.IDEA)
    # The permanent catch-all for "look into / try" items (DECISIONS #3).
    is_general = models.BooleanField(default=False, editable=False)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["name"]
        constraints = [
            models.UniqueConstraint(Lower("name"), name="project_name_unique"),
            models.UniqueConstraint(
                fields=["is_general"], condition=Q(is_general=True), name="only_one_general_project"
            ),
            models.CheckConstraint(condition=Q(state__in=ProjectState.values), name="project_state_valid"),
            models.CheckConstraint(
                condition=Q(is_general=False) | Q(state=ProjectState.BUILDING),
                name="general_project_always_building",
            ),
        ]

    def __str__(self) -> str:
        return self.name


class ItemStatus(models.TextChoices):
    OPEN = "open", "Open"
    DOING = "doing", "Doing"
    DONE = "done", "Done"


class ItemType(models.TextChoices):
    TASK = "task", "Task"
    MILESTONE = "milestone", "Milestone"


# Items that take part in a project's priority order: in a project and not done.
_RANKED = Q(project__isnull=False) & ~Q(status=ItemStatus.DONE)


class Item(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    # Empty project = in the inbox. PROTECT: a project with items can't be deleted.
    project = models.ForeignKey(
        Project, null=True, blank=True, on_delete=models.PROTECT, related_name="items"
    )
    type = models.CharField(max_length=20, choices=ItemType.choices, default=ItemType.TASK)
    # The milestone a task belongs to (DECISIONS #71). Same project and "links to a
    # milestone" are kept by the services only (#77). Deleting a milestone keeps its tasks (#79).
    milestone = models.ForeignKey(
        "self", null=True, blank=True, on_delete=models.SET_NULL, related_name="tasks"
    )
    title = models.CharField(max_length=200)
    details = models.TextField(blank=True)
    status = models.CharField(max_length=20, choices=ItemStatus.choices, default=ItemStatus.OPEN)
    # Priority, 0 = top (DECISIONS #6), counted per project and milestone (#78):
    # the project's top level, or one milestone's tasks. Only ranked items have one.
    position = models.PositiveIntegerField(null=True, blank=True)
    done_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["position", "-created_at"]
        constraints = [
            models.CheckConstraint(condition=Q(status__in=ItemStatus.values), name="item_status_valid"),
            models.CheckConstraint(condition=Q(type__in=ItemType.values), name="item_type_valid"),
            models.CheckConstraint(
                condition=Q(project__isnull=False) | Q(type=ItemType.TASK), name="inbox_items_are_tasks"
            ),
            models.CheckConstraint(
                condition=Q(milestone__isnull=True) | Q(type=ItemType.TASK), name="only_tasks_in_milestones"
            ),
            models.CheckConstraint(
                condition=Q(milestone__isnull=True) | ~Q(milestone=models.F("id")),
                name="not_its_own_milestone",
            ),
            models.CheckConstraint(
                condition=Q(project__isnull=False) | Q(status=ItemStatus.OPEN),
                name="inbox_items_are_open",
            ),
            models.CheckConstraint(
                condition=(_RANKED & Q(position__isnull=False)) | (~_RANKED & Q(position__isnull=True)),
                name="position_only_when_ranked",
            ),
            models.CheckConstraint(
                condition=Q(status=ItemStatus.DONE, done_at__isnull=False)
                | (~Q(status=ItemStatus.DONE) & Q(done_at__isnull=True)),
                name="done_at_only_when_done",
            ),
        ]

    def __str__(self) -> str:
        return self.title


class Author(models.TextChoices):
    OWNER = "owner", "Me"
    CLAUDE = "claude", "Claude"


class ActivityKind(models.TextChoices):
    CREATED = "created", "Created"
    COMMENT = "comment", "Comment"
    STATUS = "status", "Status changed"
    MOVED = "moved", "Moved"
    TYPE = "type", "Type changed"


class Activity(models.Model):
    """One entry in an item's log. Append-only: never edited, deleted only with its item."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    item = models.ForeignKey(Item, on_delete=models.CASCADE, related_name="activities")
    author = models.CharField(max_length=20, choices=Author.choices)
    kind = models.CharField(max_length=20, choices=ActivityKind.choices)
    text = models.TextField(blank=True)
    # For status changes and moves: what it was and what it became, as shown at the time.
    old_value = models.CharField(max_length=100, blank=True)
    new_value = models.CharField(max_length=100, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["created_at"]
        verbose_name_plural = "activities"
        constraints = [
            models.CheckConstraint(condition=Q(author__in=Author.values), name="activity_author_valid"),
            models.CheckConstraint(condition=Q(kind__in=ActivityKind.values), name="activity_kind_valid"),
            # DECISIONS #5: a status change needs a comment. Enforced here as well as in services.
            models.CheckConstraint(
                condition=~Q(kind__in=[ActivityKind.COMMENT, ActivityKind.STATUS]) | ~Q(text=""),
                name="comment_and_status_need_text",
            ),
        ]

    def __str__(self) -> str:
        return f"{self.get_kind_display()} by {self.get_author_display()}"
